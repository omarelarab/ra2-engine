// Q3 (CMake parity): no a*b+c -> FMA fusion on arm64, so the float math, the
// saves and the lockstep simulation match the desktop and Android builds.
let fpFlags: [CXXSetting] = [.unsafeFlags(["-ffp-contract=off"])]

let package = Package(
    name: "RA2Engine",
    platforms: [.iOS(.v15)],
    products: [
        // xtool: exactly one library product, the app.
        .library(name: "RA2Engine", targets: ["RA2Engine"]),
    ],
    targets: [
        .target(
            name: "SDL2",
            path: "ios/Vendor/SDL2",
            // (fetch_sdl2.sh deletes src/hidapi/testgui: SwiftPM scans the
            // whole target folder for resources, and its English.lproj makes
            // SwiftPM demand defaultLocalization.)
            sources: sdlSources,
            publicHeadersPath: "include",
            cSettings: [
                .headerSearchPath("include"),
                .headerSearchPath("src"),
                .headerSearchPath("src/video/khronos"),
                .define("GLES_SILENCE_DEPRECATION"),
                .define("NDEBUG", .when(configuration: .release)),
                .unsafeFlags(["-fobjc-arc", "-Wno-deprecated-declarations"]),
            ],
            linkerSettings: [
                .linkedFramework("AVFoundation"),
                .linkedFramework("AudioToolbox"),
                .linkedFramework("CoreAudio"),
                .linkedFramework("CoreBluetooth"),
                .linkedFramework("CoreFoundation"),
                .linkedFramework("CoreGraphics"),
                .linkedFramework("CoreHaptics"),
                .linkedFramework("CoreMotion"),
                .linkedFramework("CoreVideo"),
                .linkedFramework("Foundation"),
                .linkedFramework("GameController"),
                .linkedFramework("Metal"),
                .linkedFramework("OpenGLES"),
                .linkedFramework("QuartzCore"),
                .linkedFramework("UIKit"),
            ]
        ),
        .target(
            name: "RA2Assets",
            path: "src",
            // SwiftPM rejects a public-headers dir outside the target (and a
            // missing default "include"); the headers the engine uses live in
            // <repo>/include/ra2assets and are reached by headerSearchPath.
            publicHeadersPath: ".",
            cxxSettings: [
                .headerSearchPath("../include"),
                .define("NDEBUG", .when(configuration: .release)),
            ] + fpFlags
        ),
        .target(
            name: "RA2Engine",
            dependencies: ["SDL2", "RA2Assets"],
            path: "engine",
            // main.cpp is compiled through ios_main_unit.cpp (see there).
            exclude: ["main.cpp"],
            publicHeadersPath: ".",   // as RA2Assets (nothing imports the module)
            cSettings: [
                .define("RA2_IOS"),
                .unsafeFlags(["-fobjc-arc"]),   // platform_ios.mm
            ],
            cxxSettings: [
                .headerSearchPath("."),
                .headerSearchPath("../include"),
                .headerSearchPath("../third_party"),
                .headerSearchPath("../ios/generated"),   // build.sh output (above)
                .define("RA2_IOS"),
                .define("NDEBUG", .when(configuration: .release)),
                .unsafeFlags(["-fobjc-arc", "-include", "ra2_build_info.h"]),
            ] + fpFlags,
            linkerSettings: [
                .linkedFramework("Foundation"),
                .linkedFramework("UIKit"),
                .linkedFramework("UniformTypeIdentifiers"),
            ]
        ),
    ],
    cLanguageStandard: .gnu11,
    cxxLanguageStandard: .cxx17
)
